"""Compile the approved semantic icon manifest into RoundedIcons paths.

Usage: python scripts/generate_rounded_icons.py path/to/manifest.json
The generated header is self-contained; the application never reads the manifest.
"""
from pathlib import Path
import hashlib
import json
import sys


def identifier(value):
    return ''.join(part.title() for part in value.split('-'))


def generate(manifest_path):
    raw = manifest_path.read_bytes()
    manifest = json.loads(raw)
    icons = manifest['icons']
    ids = [icon['id'] for icon in icons]
    assert len(ids) == len(set(ids)) == 212
    aliases = {
        'Search': 'Find', 'Context': 'BlockAssociations', 'Hierarchy': 'Instance',
        'Signals': 'Signal', 'Wave': 'BlockWave', 'Connections': 'SignalTrace',
        'Info': 'Information', 'Success': 'Apply', 'Change': 'EditSlots',
        'Left': 'Back', 'Right': 'Forward', 'Down': 'TreeExpanded', 'Up': 'GraphParent',
        'Expand': 'MaximizeSplit', 'Collapse': 'MergeSplit', 'Restore': 'RestoreWindow',
        'Grid': 'Templates', 'Sidebar': 'LeftDrawer', 'OpenProject': 'OpenWorkspace',
        'KernelGraph': 'SignalTrace', 'ModuleGraph': 'ModuleDiagram',
        'HotspotGraph': 'SignalHeatmap', 'IpCatalog': 'IpLibrary',
        'BuildInputs': 'SimulationFile', 'Simulation': 'SimulationTop',
        'Port': 'InputPort', 'Grip': 'DragHandle',
    }
    lines = ['// Generated by scripts/generate_rounded_icons.py. Do not edit glyph paths.',
             '// Approved ICON1 manifest SHA256: ' + hashlib.sha256(raw).hexdigest(),
             '#pragma once', '#include <array>', '#include <QHash>',
             '#include <QPainterPath>', '#include <QString>', 'namespace RoundedIcons {',
             'enum Kind {']
    lines += ['    ' + identifier(i) + ',' for i in ids]
    lines += ['    CatalogSize,']
    lines += [f'    {a} = {b},' for a, b in aliases.items()]
    lines += ['};', 'inline const QPainterPath& glyph(Kind kind) {',
              '    static const auto paths = [] {',
              '        std::array<QPainterPath, CatalogSize> result;']
    for icon in icons:
        lines.append('        { auto& p = result[' + identifier(icon['id']) + '];')
        for op in icon['ops']:
            v = op['v']
            values = ', '.join(str(x) for x in v)
            if op['t'] == 'line':
                lines.append(f'            p.moveTo({v[0]}, {v[1]}); p.lineTo({v[2]}, {v[3]});')
            elif op['t'] == 'rect':
                lines.append(f'            p.addRoundedRect(QRectF({", ".join(str(x) for x in v[:4])}), {v[4]}, {v[4]});')
            elif op['t'] == 'circle':
                lines.append(f'            p.addEllipse(QPointF({v[0]}, {v[1]}), {v[2]}, {v[2]});')
            elif op['t'] == 'path':
                for command in v:
                    method = {'M': 'moveTo', 'L': 'lineTo', 'Q': 'quadTo', 'C': 'cubicTo', 'Z': 'closeSubpath'}[command[0]]
                    lines.append(f'            p.{method}({", ".join(str(x) for x in command[1:])});')
            else:
                raise ValueError(op)
        lines.append('        }')
    lines += ['        return result;', '    }();',
              '    static const QPainterPath empty;',
              '    return kind >= 0 && kind < CatalogSize ? paths[kind] : empty;', '}',
              'inline Kind actionKind(const QString& id) {',
              '    static const QHash<QString, Kind> actions{']
    lines += [f'        {{QStringLiteral("{a["id"]}"), {identifier(a["iconId"])}}},' for a in manifest['actions']]
    # Active descriptors constructed outside the manifest's explicit Specs table.
    supplements = {'edit.deleteSelection': 'Delete', 'rtl.rename': 'Rename',
                   'rtl.connection.transform': 'ConnectInstances',
                   'view.commandMode': 'ActionCatalog', 'view.globalControl': 'ActionCatalog',
                   'signal.trace.exportImage': 'ExportGraph', 'signal.trace.exportHeatmap': 'Export'}
    for suffix in ('reg', 'wire', 'logic', 'module', 'task', 'function', 'interface', 'macro',
                   'localparam', 'parameter', 'always', 'continuousAssign', 'typedef',
                   'enumValue', 'enumType', 'enumVariable', 'structMember',
                   'packedStructType', 'unpackedStructType', 'packedStructVariable', 'unpackedStructVariable'):
        supplements['completion.' + suffix] = 'SearchSymbols'
    lines += [f'        {{QStringLiteral("{key}"), {kind}}},' for key, kind in supplements.items()]
    labels = {}
    for i in icons:
        labels[i['name'].casefold()] = identifier(i['id'])
    for a in manifest['actions']:
        labels[a['name'].casefold()] = identifier(a['iconId'])
    lines += ['    };', '    return actions.value(id, CatalogSize);', '}',
              'inline Kind labelKind(QString text) {',
              '    text = text.section(QLatin1Char(\'\\t\'), 0, 0).remove(QLatin1Char(\'&\')).trimmed();',
              '    if (text.endsWith(QStringLiteral("..."))) text.chop(3);',
              '    if (text.endsWith(QChar(0x2026))) text.chop(1);',
              '    static const QHash<QString, Kind> labels{']
    lines += [f'        {{QStringLiteral({json.dumps(label, ensure_ascii=False)}), {kind}}},' for label, kind in sorted(labels.items())]
    lines += ['    };', '    return labels.value(text.trimmed().toCaseFolded(), CatalogSize);', '}',
              'inline const char* semanticId(Kind kind) {',
              '    static constexpr const char* ids[]{']
    lines += [f'        "{i}",' for i in ids]
    lines += ['    };', '    return kind >= 0 && kind < CatalogSize ? ids[kind] : "";', '}', '}']
    target = Path(__file__).resolve().parents[1] / 'src/ui/roundediconcatalog.h'
    target.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'{len(icons)} glyphs, {len(manifest["actions"])} action mappings -> {target}')


if __name__ == '__main__':
    generate(Path(sys.argv[1]))
